// Turns assets/scrabble/words.txt into lib/game/scrabble/scrabble_words.g.dart.
//
// The word list lives in Scrabble's own code rather than in the app's assets,
// so it's only in apps that include Scrabble (Flutter drops unused code from
// every other app, but bundles every asset in all of them).
//
// Run after changing words.txt:
//   dart run tools/gen_scrabble_words.dart
import 'dart:io';

void main() {
  final words = File('assets/scrabble/words.txt')
      .readAsLinesSync()
      .map((w) => w.trim().toUpperCase())
      .where((w) => w.length >= 2 && RegExp(r'^[A-Z]+$').hasMatch(w))
      .toList();
  final out = StringBuffer()
    ..writeln('// GENERATED by tools/gen_scrabble_words.dart from assets/scrabble/words.txt')
    ..writeln('// (ENABLE word list, public domain). Do not edit by hand.')
    ..writeln()
    ..writeln('/// ${words.length} words, uppercase, one per line.')
    ..write("const scrabbleWordList = '''")
    ..write(words.join('\n'))
    ..writeln("''';");
  File('lib/game/scrabble/scrabble_words.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${words.length} words.');
}
